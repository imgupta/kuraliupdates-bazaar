-- Safe, non-destructive Oracle setup for server-backed bargaining chat.
-- This script is intentionally separate from schema-oracle.sql because that file
-- drops and recreates the full application schema and must not be run on live data.
DECLARE
  table_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO table_count FROM USER_TABLES WHERE TABLE_NAME = 'NEGOTIATION_CHATS';
  IF table_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE NEGOTIATION_CHATS (
      CHAT_ID VARCHAR2(64) PRIMARY KEY,
      PRODUCT_ID VARCHAR2(64) NOT NULL REFERENCES PRODUCTS(PRODUCT_ID),
      SELLER_ID VARCHAR2(64) NOT NULL REFERENCES SELLERS(SELLER_ID),
      BUYER_NAME VARCHAR2(150) NOT NULL,
      BUYER_EMAIL VARCHAR2(255) NOT NULL,
      CURRENT_AGREED_PRICE NUMBER(10,2),
      LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )';
  END IF;
END;
/
DECLARE
  table_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO table_count FROM USER_TABLES WHERE TABLE_NAME = 'CHAT_MESSAGES';
  IF table_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE CHAT_MESSAGES (
      MESSAGE_ID VARCHAR2(64) PRIMARY KEY,
      CHAT_ID VARCHAR2(64) NOT NULL REFERENCES NEGOTIATION_CHATS(CHAT_ID) ON DELETE CASCADE,
      SENDER_ROLE VARCHAR2(20) NOT NULL CHECK (SENDER_ROLE IN (''BUYER'', ''SELLER'')),
      SENDER_NAME VARCHAR2(150) NOT NULL,
      MESSAGE_TEXT CLOB NOT NULL,
      OFFER_PRICE NUMBER(10,2),
      OFFER_STATUS VARCHAR2(20) CHECK (OFFER_STATUS IN (''PENDING'', ''ACCEPTED'', ''REJECTED'', ''COUNTERED'')),
      CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )';
  END IF;
END;
/
DECLARE
  index_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO index_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_CHAT_SELLER';
  IF index_count = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IDX_CHAT_SELLER ON NEGOTIATION_CHATS(SELLER_ID)'; END IF;
  SELECT COUNT(*) INTO index_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_CHAT_PROD';
  IF index_count = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IDX_CHAT_PROD ON NEGOTIATION_CHATS(PRODUCT_ID)'; END IF;
  SELECT COUNT(*) INTO index_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_CHAT_BUYER';
  IF index_count = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IDX_CHAT_BUYER ON NEGOTIATION_CHATS(BUYER_EMAIL)';
  END IF;
  SELECT COUNT(*) INTO index_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_MSG_CHAT';
  IF index_count = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IDX_MSG_CHAT ON CHAT_MESSAGES(CHAT_ID)'; END IF;
END;
/
