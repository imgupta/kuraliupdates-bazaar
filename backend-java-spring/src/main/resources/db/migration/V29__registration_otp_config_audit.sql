-- Append-only audit history for administrator changes to registration OTP policy.
CREATE TABLE SELLER_REGISTRATION_OTP_CONFIG_AUDIT (
    AUDIT_ID VARCHAR2(36) PRIMARY KEY,
    EMAIL_OTP_ENABLED NUMBER(1) NOT NULL,
    MOBILE_OTP_ENABLED NUMBER(1) NOT NULL,
    PREVIOUS_EMAIL_OTP_ENABLED NUMBER(1) NOT NULL,
    PREVIOUS_MOBILE_OTP_ENABLED NUMBER(1) NOT NULL,
    CHANGED_BY VARCHAR2(150) NOT NULL,
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_REG_OTP_AUDIT_EMAIL CHECK (EMAIL_OTP_ENABLED IN (0,1)),
    CONSTRAINT CK_REG_OTP_AUDIT_MOBILE CHECK (MOBILE_OTP_ENABLED IN (0,1)),
    CONSTRAINT CK_REG_OTP_AUDIT_PREV_EMAIL CHECK (PREVIOUS_EMAIL_OTP_ENABLED IN (0,1)),
    CONSTRAINT CK_REG_OTP_AUDIT_PREV_MOBILE CHECK (PREVIOUS_MOBILE_OTP_ENABLED IN (0,1))
);
CREATE INDEX IDX_REG_OTP_AUDIT_TIME ON SELLER_REGISTRATION_OTP_CONFIG_AUDIT (CHANGED_AT DESC);
