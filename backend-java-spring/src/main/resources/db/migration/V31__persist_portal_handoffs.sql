-- Persist one-time cross-portal handoffs so codes work across restarts and instances.
-- Store only a SHA-256 digest of the high-entropy code; never persist the redeemable code.
CREATE TABLE AUTH_PORTAL_HANDOFFS (
    CODE_HASH VARCHAR2(64) NOT NULL,
    SESSION_TOKEN VARCHAR2(128) NOT NULL,
    ROLE VARCHAR2(30) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    CONSUMED_AT TIMESTAMP NULL,
    CONSTRAINT PK_AUTH_PORTAL_HANDOFFS PRIMARY KEY (CODE_HASH),
    CONSTRAINT CK_AUTH_PORTAL_HANDOFF_ROLE CHECK (ROLE IN ('BUYER','SELLER','DELIVERY','PROFESSIONAL','ADMIN'))
);

CREATE INDEX IDX_AUTH_PORTAL_HANDOFF_EXPIRY ON AUTH_PORTAL_HANDOFFS (EXPIRES_AT);
