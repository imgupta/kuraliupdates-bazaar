-- Admin order operations: immutable history, private support notes, refund ledger and durable customer notice outbox.
CREATE TABLE ADMIN_ORDER_EVENTS (
  EVENT_ID VARCHAR2(36) PRIMARY KEY,
  ORDER_ID VARCHAR2(64) NOT NULL,
  EVENT_TYPE VARCHAR2(40) NOT NULL,
  DETAILS VARCHAR2(2000),
  ACTOR_EMAIL VARCHAR2(255) NOT NULL,
  OCCURRED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IDX_ADMIN_ORDER_EVENTS ON ADMIN_ORDER_EVENTS(ORDER_ID,OCCURRED_AT DESC);

CREATE TABLE ADMIN_ORDER_NOTES (
  NOTE_ID VARCHAR2(36) PRIMARY KEY,
  ORDER_ID VARCHAR2(64) NOT NULL,
  NOTE_TEXT VARCHAR2(2000) NOT NULL,
  CREATED_BY VARCHAR2(255) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IDX_ADMIN_ORDER_NOTES ON ADMIN_ORDER_NOTES(ORDER_ID,CREATED_AT DESC);

CREATE TABLE ADMIN_ORDER_REFUNDS (
  REFUND_ID VARCHAR2(36) PRIMARY KEY,
  ORDER_ID VARCHAR2(64) NOT NULL,
  AMOUNT NUMBER(10,2) NOT NULL CHECK (AMOUNT > 0),
  STATUS VARCHAR2(20) NOT NULL CHECK (STATUS IN ('REQUESTED','PROCESSED')),
  REASON VARCHAR2(500),
  TRANSACTION_REFERENCE VARCHAR2(150),
  REQUESTED_BY VARCHAR2(255) NOT NULL,
  REQUESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PROCESSED_BY VARCHAR2(255),
  PROCESSED_AT TIMESTAMP
);
CREATE INDEX IDX_ADMIN_ORDER_REFUNDS ON ADMIN_ORDER_REFUNDS(ORDER_ID,REQUESTED_AT DESC);

CREATE TABLE ADMIN_ORDER_NOTICE_OUTBOX (
  NOTICE_ID VARCHAR2(36) PRIMARY KEY,
  ORDER_ID VARCHAR2(64) NOT NULL,
  RECIPIENT_EMAIL VARCHAR2(255),
  RECIPIENT_PHONE VARCHAR2(30),
  EVENT_TYPE VARCHAR2(40) NOT NULL,
  MESSAGE_TEXT VARCHAR2(1000) NOT NULL,
  DELIVERY_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  SENT_AT TIMESTAMP,
  LAST_ERROR VARCHAR2(1000),
  CONSTRAINT CK_ADMIN_ORDER_NOTICE_STATUS CHECK (DELIVERY_STATUS IN ('PENDING','SENT','FAILED'))
);
CREATE INDEX IDX_ADMIN_ORDER_NOTICE_PENDING ON ADMIN_ORDER_NOTICE_OUTBOX(DELIVERY_STATUS,CREATED_AT);
