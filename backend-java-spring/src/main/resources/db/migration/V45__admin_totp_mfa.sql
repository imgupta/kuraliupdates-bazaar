CREATE TABLE ADMIN_MFA_FACTORS (
    USER_ID               VARCHAR2(64)   NOT NULL,
    ENCRYPTED_SECRET      VARCHAR2(512)  NOT NULL,
    ENABLED               NUMBER(1)      DEFAULT 0 NOT NULL,
    STEP_UP_TOKEN_HASH    VARCHAR2(64),
    STEP_UP_SESSION_HASH  VARCHAR2(64),
    STEP_UP_EXPIRES_AT    TIMESTAMP,
    CREATED_AT            TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_ADMIN_MFA_FACTORS PRIMARY KEY (USER_ID),
    CONSTRAINT CK_ADMIN_MFA_ENABLED CHECK (ENABLED IN (0, 1))
);

CREATE TABLE ADMIN_MFA_RECOVERY_CODES (
    CODE_HASH   VARCHAR2(64) NOT NULL,
    USER_ID     VARCHAR2(64) NOT NULL,
    USED_AT     TIMESTAMP,
    CREATED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_ADMIN_MFA_RECOVERY_CODES PRIMARY KEY (CODE_HASH)
);

CREATE INDEX IDX_ADMIN_MFA_RECOVERY_USER
    ON ADMIN_MFA_RECOVERY_CODES (USER_ID, USED_AT);
