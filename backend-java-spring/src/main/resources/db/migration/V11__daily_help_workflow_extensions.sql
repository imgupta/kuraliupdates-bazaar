-- Recovery-safe Daily Help extensions.
-- This migration may be retried after Oracle DDL has partially applied.

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'DAILY_HELP_BOOKINGS'
       AND COLUMN_NAME = 'OTP_EXPIRES_AT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE DAILY_HELP_BOOKINGS ADD (OTP_EXPIRES_AT TIMESTAMP)';
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'DAILY_HELP_BOOKINGS'
       AND COLUMN_NAME = 'OTP_ATTEMPTS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE DAILY_HELP_BOOKINGS ADD (OTP_ATTEMPTS NUMBER(5) DEFAULT 0 NOT NULL)';
    END IF;
END;
