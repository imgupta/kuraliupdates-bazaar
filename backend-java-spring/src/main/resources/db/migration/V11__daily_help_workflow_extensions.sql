DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'DAILY_HELP_PROFESSIONAL_SLOTS';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE DAILY_HELP_PROFESSIONAL_SLOTS (
                SLOT_ID VARCHAR2(64 CHAR) NOT NULL,
                PROFESSIONAL_ID VARCHAR2(64 CHAR) NOT NULL,
                SLOT_DATE DATE NOT NULL,
                START_TIME TIMESTAMP NOT NULL,
                END_TIME TIMESTAMP NOT NULL,
                STATUS VARCHAR2(20 CHAR) DEFAULT 'AVAILABLE' NOT NULL,
                BOOKING_ID VARCHAR2(64 CHAR),
                CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_DH_PROF_SLOT PRIMARY KEY (SLOT_ID),
                CONSTRAINT FK_DH_SLOT_PROF FOREIGN KEY (PROFESSIONAL_ID)
                    REFERENCES DAILY_HELP_PROFESSIONALS(PROFESSIONAL_ID) ON DELETE CASCADE,
                CONSTRAINT UK_DH_PROF_SLOT UNIQUE
                    (PROFESSIONAL_ID, SLOT_DATE, START_TIME, END_TIME)
            )
        ]';
    END IF;
END;
