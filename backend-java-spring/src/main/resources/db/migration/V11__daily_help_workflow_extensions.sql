DECLARE
    v_count NUMBER;
BEGIN
    -- Oracle rejects an index when the same column list is already indexed,
    -- even if that existing index has a different name. Check both name and
    -- ordered column list so this migration is safe after partial attempts.

    SELECT COUNT(*) INTO v_count
      FROM USER_INDEXES i
     WHERE i.TABLE_NAME = 'DAILY_HELP_PROFESSIONAL_SLOTS'
       AND (i.INDEX_NAME = 'IDX_DH_SLOT_LOOKUP'
            OR (SELECT LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION)
                  FROM USER_IND_COLUMNS c
                 WHERE c.INDEX_NAME = i.INDEX_NAME
                   AND c.TABLE_NAME = i.TABLE_NAME)
               = 'SLOT_DATE,STATUS,PROFESSIONAL_ID');
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_DH_SLOT_LOOKUP ON DAILY_HELP_PROFESSIONAL_SLOTS (SLOT_DATE, STATUS, PROFESSIONAL_ID)';
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_INDEXES i
     WHERE i.TABLE_NAME = 'DAILY_HELP_BOOKINGS'
       AND (i.INDEX_NAME = 'IDX_DH_BOOK_PROF'
            OR (SELECT LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION)
                  FROM USER_IND_COLUMNS c
                 WHERE c.INDEX_NAME = i.INDEX_NAME
                   AND c.TABLE_NAME = i.TABLE_NAME)
               = 'PROFESSIONAL_ID,STATUS,SCHEDULED_START');
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_DH_BOOK_PROF ON DAILY_HELP_BOOKINGS (PROFESSIONAL_ID, STATUS, SCHEDULED_START)';
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_INDEXES i
     WHERE i.TABLE_NAME = 'DAILY_HELP_BOOKINGS'
       AND (i.INDEX_NAME = 'IDX_DH_BOOK_MATCH'
            OR (SELECT LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION)
                  FROM USER_IND_COLUMNS c
                 WHERE c.INDEX_NAME = i.INDEX_NAME
                   AND c.TABLE_NAME = i.TABLE_NAME)
               = 'STATUS,LOCALITY,SCHEDULED_START');
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_DH_BOOK_MATCH ON DAILY_HELP_BOOKINGS (STATUS, LOCALITY, SCHEDULED_START)';
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_INDEXES i
     WHERE i.TABLE_NAME = 'DAILY_HELP_SERVICES'
       AND (i.INDEX_NAME = 'IDX_DH_SERVICE_ACTIVE'
            OR (SELECT LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION)
                  FROM USER_IND_COLUMNS c
                 WHERE c.INDEX_NAME = i.INDEX_NAME
                   AND c.TABLE_NAME = i.TABLE_NAME)
               = 'ACTIVE,CATEGORY');
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_DH_SERVICE_ACTIVE ON DAILY_HELP_SERVICES (ACTIVE, CATEGORY)';
    END IF;
END;
