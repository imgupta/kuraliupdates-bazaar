CREATE TABLE SELLER_SERVICE_AREA_CONFIG (
  CONFIG_KEY VARCHAR2(64) PRIMARY KEY,
  CENTER_LATITUDE NUMBER(10,7) NOT NULL,
  CENTER_LONGITUDE NUMBER(10,7) NOT NULL,
  RADIUS_KM NUMBER(6,2) NOT NULL,
  ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
  CONFIG_VERSION NUMBER(10) DEFAULT 1 NOT NULL,
  UPDATED_BY VARCHAR2(64),
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CK_SELLER_AREA_RADIUS CHECK (RADIUS_KM > 0 AND RADIUS_KM <= 100),
  CONSTRAINT CK_SELLER_AREA_ENABLED CHECK (ENABLED IN (0,1))
);

