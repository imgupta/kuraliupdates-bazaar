-- Admin-controlled, independent OTP requirements for seller registration.
CREATE TABLE SELLER_REGISTRATION_OTP_CONFIG (
    CONFIG_ID VARCHAR2(20) PRIMARY KEY,
    EMAIL_OTP_ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
    MOBILE_OTP_ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
    UPDATED_BY VARCHAR2(150),
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_SELLER_OTP_EMAIL CHECK (EMAIL_OTP_ENABLED IN (0,1)),
    CONSTRAINT CK_SELLER_OTP_MOBILE CHECK (MOBILE_OTP_ENABLED IN (0,1))
);
