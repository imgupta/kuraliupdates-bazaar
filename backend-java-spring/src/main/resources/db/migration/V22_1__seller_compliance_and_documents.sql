ALTER TABLE SELLERS ADD (
  BUSINESS_TYPE VARCHAR2(30),
  REGISTERED_BUSINESS_NAME VARCHAR2(255),
  SHOP_NUMBER VARCHAR2(80),
  WARD_NUMBER VARCHAR2(40),
  STREET_LOCALITY VARCHAR2(255),
  PIN_CODE VARCHAR2(6),
  LANDMARK VARCHAR2(255),
  GST_VERIFICATION_STATUS VARCHAR2(20) DEFAULT 'NOT_SUBMITTED' NOT NULL,
  FSSAI_VERIFICATION_STATUS VARCHAR2(20) DEFAULT 'NOT_SUBMITTED' NOT NULL,
  FSSAI_LICENSE_TYPE VARCHAR2(40),
  FSSAI_EXPIRY_DATE DATE,
  OPENING_TIME VARCHAR2(5),
  CLOSING_TIME VARCHAR2(5),
  WEEKLY_CLOSED_DAY VARCHAR2(20),
  PREPARATION_MINUTES NUMBER(5),
  AGREEMENT_VERSION VARCHAR2(40),
  AGREEMENT_ACCEPTED_AT TIMESTAMP,
  AGREEMENT_ACCEPTED_IP VARCHAR2(64)
);
CREATE TABLE SELLER_DOCUMENTS (
  DOCUMENT_ID VARCHAR2(64) PRIMARY KEY,
  SELLER_ID VARCHAR2(64) NOT NULL,
  DOCUMENT_TYPE VARCHAR2(40) NOT NULL,
  FILE_NAME VARCHAR2(255) NOT NULL,
  CONTENT_TYPE VARCHAR2(100) NOT NULL,
  FILE_SIZE NUMBER(10) NOT NULL,
  DOCUMENT_DATA BLOB NOT NULL,
  VERIFICATION_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  VERIFIED_BY VARCHAR2(64),
  VERIFIED_AT TIMESTAMP,
  REJECTION_REASON VARCHAR2(1000),
  UPLOADED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_SELLER_DOC_SELLER FOREIGN KEY (SELLER_ID) REFERENCES SELLERS(SELLER_ID) ON DELETE CASCADE,
  CONSTRAINT CK_SELLER_DOC_STATUS CHECK (VERIFICATION_STATUS IN ('PENDING','VERIFIED','REJECTED')),
  CONSTRAINT CK_SELLER_DOC_TYPE CHECK (DOCUMENT_TYPE IN ('GST_CERTIFICATE','FSSAI_CERTIFICATE','SHOP_FRONT_PHOTO','SHOP_INTERIOR_PHOTO','TRADE_LICENSE','UDYAM_CERTIFICATE'))
);
CREATE INDEX IDX_SELLER_DOC_SELLER ON SELLER_DOCUMENTS(SELLER_ID, DOCUMENT_TYPE);
