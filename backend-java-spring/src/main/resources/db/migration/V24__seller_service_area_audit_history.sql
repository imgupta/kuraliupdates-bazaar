CREATE TABLE SELLER_SERVICE_AREA_CONFIG_HISTORY (
  HISTORY_ID VARCHAR2(64) PRIMARY KEY,
  CONFIG_KEY VARCHAR2(64) NOT NULL,
  CENTER_LATITUDE NUMBER(10,7) NOT NULL,
  CENTER_LONGITUDE NUMBER(10,7) NOT NULL,
  RADIUS_KM NUMBER(6,2) NOT NULL,
  ENABLED NUMBER(1) NOT NULL,
  CONFIG_VERSION NUMBER(10) NOT NULL,
  UPDATED_BY VARCHAR2(64),
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_SELLER_AREA_HISTORY FOREIGN KEY (CONFIG_KEY) REFERENCES SELLER_SERVICE_AREA_CONFIG(CONFIG_KEY),
  CONSTRAINT UQ_SELLER_AREA_VERSION UNIQUE (CONFIG_KEY, CONFIG_VERSION)
);

INSERT INTO SELLER_SERVICE_AREA_CONFIG_HISTORY
  (HISTORY_ID, CONFIG_KEY, CENTER_LATITUDE, CENTER_LONGITUDE, RADIUS_KM, ENABLED, CONFIG_VERSION, UPDATED_BY, UPDATED_AT)
SELECT 'SELLER_AREA_INITIAL_V' || TO_CHAR(CONFIG_VERSION), CONFIG_KEY, CENTER_LATITUDE,
       CENTER_LONGITUDE, RADIUS_KM, ENABLED, CONFIG_VERSION, UPDATED_BY, UPDATED_AT
FROM SELLER_SERVICE_AREA_CONFIG;
