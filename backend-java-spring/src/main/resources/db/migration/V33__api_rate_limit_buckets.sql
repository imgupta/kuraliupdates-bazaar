CREATE TABLE API_RATE_LIMIT_BUCKETS (
    BUCKET_KEY VARCHAR2(64) NOT NULL,
    WINDOW_START TIMESTAMP(6) NOT NULL,
    REQUEST_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    EXPIRES_AT TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_API_RATE_LIMIT_BUCKETS PRIMARY KEY (BUCKET_KEY, WINDOW_START)
);
CREATE INDEX IDX_API_RATE_LIMIT_EXPIRES ON API_RATE_LIMIT_BUCKETS(EXPIRES_AT);
