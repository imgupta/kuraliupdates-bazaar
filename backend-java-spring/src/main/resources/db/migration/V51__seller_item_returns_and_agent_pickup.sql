-- Dedicated item-level seller returns with agent pickup and seller-funded original-mode refunds.
CREATE TABLE SELLER_RETURN_CASES (
  RETURN_ID VARCHAR2(64) PRIMARY KEY,
  ORDER_ID VARCHAR2(64) NOT NULL,
  ITEM_ID VARCHAR2(64) NOT NULL,
  BUYER_USER_ID VARCHAR2(64) NOT NULL,
  SELLER_ID VARCHAR2(64) NOT NULL,
  QUANTITY NUMBER(10) NOT NULL,
  RETURN_AMOUNT NUMBER(12,2) NOT NULL,
  ORIGINAL_PAYMENT_METHOD VARCHAR2(30) NOT NULL,
  REASON VARCHAR2(500) NOT NULL,
  STATUS VARCHAR2(40) NOT NULL,
  SELLER_DECISION_REASON VARCHAR2(500),
  DELIVERY_AGENT_ID VARCHAR2(64),
  PICKUP_REFERENCE VARCHAR2(100),
  SELLER_RECEIPT_REFERENCE VARCHAR2(100),
  REFUND_METHOD VARCHAR2(30),
  REFUND_REFERENCE VARCHAR2(100),
  REFUND_COMPLETED_AT TIMESTAMP,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_RETURN_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID),
  CONSTRAINT FK_RETURN_ITEM FOREIGN KEY (ITEM_ID) REFERENCES ORDER_ITEMS(ITEM_ID),
  CONSTRAINT FK_RETURN_SELLER FOREIGN KEY (SELLER_ID) REFERENCES SELLERS(SELLER_ID),
  CONSTRAINT FK_RETURN_AGENT FOREIGN KEY (DELIVERY_AGENT_ID) REFERENCES DELIVERY_AGENTS(AGENT_ID),
  CONSTRAINT CK_RETURN_QTY CHECK (QUANTITY > 0),
  CONSTRAINT CK_RETURN_AMOUNT CHECK (RETURN_AMOUNT >= 0)
);
CREATE INDEX IDX_RETURN_BUYER ON SELLER_RETURN_CASES(BUYER_USER_ID, CREATED_AT);
CREATE INDEX IDX_RETURN_SELLER ON SELLER_RETURN_CASES(SELLER_ID, STATUS, CREATED_AT);
CREATE INDEX IDX_RETURN_AGENT ON SELLER_RETURN_CASES(DELIVERY_AGENT_ID, STATUS);
CREATE TABLE SELLER_RETURN_EVENTS (
  EVENT_ID VARCHAR2(64) PRIMARY KEY,
  RETURN_ID VARCHAR2(64) NOT NULL,
  ACTOR_USER_ID VARCHAR2(64) NOT NULL,
  ACTOR_ROLE VARCHAR2(20) NOT NULL,
  EVENT_TYPE VARCHAR2(50) NOT NULL,
  FROM_STATUS VARCHAR2(40),
  TO_STATUS VARCHAR2(40) NOT NULL,
  REFERENCE_VALUE VARCHAR2(100),
  NOTE VARCHAR2(500),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_RETURN_EVENT_CASE FOREIGN KEY (RETURN_ID) REFERENCES SELLER_RETURN_CASES(RETURN_ID)
);
CREATE INDEX IDX_RETURN_EVENTS ON SELLER_RETURN_EVENTS(RETURN_ID, CREATED_AT);
