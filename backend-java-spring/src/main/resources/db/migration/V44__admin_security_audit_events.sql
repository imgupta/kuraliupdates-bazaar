-- Append-only security audit trail for administrator mutations.
CREATE TABLE SECURITY_AUDIT_EVENTS (
    EVENT_ID          VARCHAR2(36)   NOT NULL,
    ACTOR_USER_ID     VARCHAR2(64),
    ACTOR_EMAIL       VARCHAR2(255),
    EVENT_CATEGORY    VARCHAR2(40)   NOT NULL,
    ACTION            VARCHAR2(120)  NOT NULL,
    TARGET_TYPE       VARCHAR2(80),
    TARGET_ID         VARCHAR2(128),
    REQUEST_METHOD    VARCHAR2(10)   NOT NULL,
    REQUEST_PATH      VARCHAR2(500)  NOT NULL,
    OUTCOME           VARCHAR2(20)   NOT NULL,
    HTTP_STATUS       NUMBER(3),
    DETAILS            VARCHAR2(1000),
    OCCURRED_AT       TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_SECURITY_AUDIT_EVENTS PRIMARY KEY (EVENT_ID),
    CONSTRAINT CK_SECURITY_AUDIT_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX IDX_SECURITY_AUDIT_ACTOR_TIME
    ON SECURITY_AUDIT_EVENTS (ACTOR_USER_ID, OCCURRED_AT);

CREATE INDEX IDX_SECURITY_AUDIT_TARGET_TIME
    ON SECURITY_AUDIT_EVENTS (TARGET_TYPE, TARGET_ID, OCCURRED_AT);

CREATE INDEX IDX_SECURITY_AUDIT_TIME
    ON SECURITY_AUDIT_EVENTS (OCCURRED_AT);
