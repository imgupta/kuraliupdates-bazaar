CREATE TABLE SELLER_APPLICATIONS (
  APPLICATION_ID VARCHAR2(64) PRIMARY KEY,
  OWNER_NAME VARCHAR2(150) NOT NULL,
  EMAIL VARCHAR2(254) NOT NULL,
  PHONE VARCHAR2(10) NOT NULL,
  SHOP_NAME VARCHAR2(150) NOT NULL,
  STATUS VARCHAR2(24) DEFAULT 'DRAFT' NOT NULL,
  STATUS_REASON VARCHAR2(1000),
  ASSIGNED_TO VARCHAR2(150),
  APPLICATION_JSON CLOB NOT NULL,
  ACCESS_TOKEN_HASH VARCHAR2(64) NOT NULL,
  CREATED_BY VARCHAR2(150) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_SELLER_APP_STATUS CHECK (STATUS IN ('DRAFT','IN_PROGRESS','SUBMITTED','UNDER_REVIEW','ACTION_REQUIRED','APPROVED','REJECTED'))
);
CREATE INDEX IDX_SELLER_APP_STATUS ON SELLER_APPLICATIONS (STATUS, UPDATED_AT);
CREATE INDEX IDX_SELLER_APP_CONTACT ON SELLER_APPLICATIONS (EMAIL, PHONE);

CREATE TABLE SELLER_APPLICATION_DOCUMENTS (
  DOCUMENT_ID VARCHAR2(64) PRIMARY KEY,
  APPLICATION_ID VARCHAR2(64) NOT NULL,
  DOCUMENT_TYPE VARCHAR2(40) NOT NULL,
  FILE_NAME VARCHAR2(255) NOT NULL,
  CONTENT_TYPE VARCHAR2(100) NOT NULL,
  FILE_SIZE NUMBER(12) NOT NULL,
  DOCUMENT_DATA BLOB NOT NULL,
  SCAN_STATUS VARCHAR2(20) DEFAULT 'QUARANTINED' NOT NULL,
  VERIFICATION_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  REJECTION_REASON VARCHAR2(1000),
  UPLOADED_BY VARCHAR2(150) NOT NULL,
  UPLOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  SCANNED_AT TIMESTAMP,
  CONSTRAINT FK_SELLER_APP_DOC FOREIGN KEY (APPLICATION_ID) REFERENCES SELLER_APPLICATIONS(APPLICATION_ID),
  CONSTRAINT CK_SELLER_APP_DOC_SCAN CHECK (SCAN_STATUS IN ('QUARANTINED','CLEAN','INFECTED','SCAN_FAILED')),
  CONSTRAINT CK_SELLER_APP_DOC_VERIFY CHECK (VERIFICATION_STATUS IN ('PENDING','VERIFIED','REJECTED'))
);
CREATE INDEX IDX_SELLER_APP_DOCS ON SELLER_APPLICATION_DOCUMENTS (APPLICATION_ID, UPLOADED_AT);

CREATE TABLE SELLER_APPLICATION_AUDIT (
  AUDIT_ID VARCHAR2(64) PRIMARY KEY,
  APPLICATION_ID VARCHAR2(64) NOT NULL,
  ACTOR VARCHAR2(150) NOT NULL,
  ACTION VARCHAR2(60) NOT NULL,
  DETAILS VARCHAR2(2000),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_SELLER_APP_AUDIT FOREIGN KEY (APPLICATION_ID) REFERENCES SELLER_APPLICATIONS(APPLICATION_ID)
);
CREATE INDEX IDX_SELLER_APP_AUDIT ON SELLER_APPLICATION_AUDIT (APPLICATION_ID, CREATED_AT);