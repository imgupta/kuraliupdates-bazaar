ALTER TABLE USER_SESSIONS ADD ABSOLUTE_EXPIRES_AT TIMESTAMP;

-- Preserve the existing absolute expiry and give already-active sessions up to
-- 30 minutes to refresh after this release; shorter E2E/handoff lifetimes remain shorter.
UPDATE USER_SESSIONS
   SET ABSOLUTE_EXPIRES_AT = EXPIRES_AT
 WHERE ABSOLUTE_EXPIRES_AT IS NULL;

UPDATE USER_SESSIONS
   SET EXPIRES_AT = LEAST(EXPIRES_AT, SYSTIMESTAMP + INTERVAL '30' MINUTE)
 WHERE EXPIRES_AT > SYSTIMESTAMP + INTERVAL '30' MINUTE;

ALTER TABLE USER_SESSIONS MODIFY ABSOLUTE_EXPIRES_AT NOT NULL;

CREATE INDEX IDX_USER_SESSIONS_ABSOLUTE_EXP
    ON USER_SESSIONS (ABSOLUTE_EXPIRES_AT);
