ALTER TABLE SELLERS ADD COD_ENABLED NUMBER(1) DEFAULT 1 NOT NULL CHECK (COD_ENABLED IN (0,1));

-- Seller-direct payment records. KuraliUpdates never receives or holds customer funds.
CREATE TABLE SELLER_PAYMENT_DESTINATIONS (
  DESTINATION_ID VARCHAR2(64) PRIMARY KEY,
  SELLER_ID VARCHAR2(64) NOT NULL UNIQUE REFERENCES SELLERS(SELLER_ID),
  UPI_ID VARCHAR2(128) NOT NULL,
  PAYEE_NAME VARCHAR2(150) NOT NULL,
  VERIFICATION_STATUS VARCHAR2(24) NOT NULL CHECK (VERIFICATION_STATUS IN ('PENDING_VERIFICATION','VERIFIED','REJECTED')),
  ACTIVE_FLAG NUMBER(1) DEFAULT 0 NOT NULL CHECK (ACTIVE_FLAG IN (0,1)),
  VERIFIED_BY VARCHAR2(255),
  VERIFIED_AT TIMESTAMP,
  UPDATED_BY VARCHAR2(255) NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_SELLER_UPI_ID CHECK (INSTR(UPI_ID,'@') > 1)
);

CREATE TABLE ORDER_SELLER_PAYMENTS (
  PAYMENT_ID VARCHAR2(64) PRIMARY KEY,
  ORDER_ID VARCHAR2(64) NOT NULL UNIQUE REFERENCES ORDERS(ORDER_ID),
  CHECKOUT_GROUP_ID VARCHAR2(64),
  SELLER_ID VARCHAR2(64) NOT NULL REFERENCES SELLERS(SELLER_ID),
  BUYER_EMAIL VARCHAR2(255) NOT NULL,
  EXPECTED_AMOUNT NUMBER(12,2) NOT NULL CHECK (EXPECTED_AMOUNT > 0),
  CURRENCY VARCHAR2(3) DEFAULT 'INR' NOT NULL,
  UPI_ID_SNAPSHOT VARCHAR2(128) NOT NULL,
  PAYEE_NAME_SNAPSHOT VARCHAR2(150) NOT NULL,
  PAYMENT_STATUS VARCHAR2(40) NOT NULL CHECK (PAYMENT_STATUS IN
    ('AWAITING_PAYMENT','AWAITING_SELLER_CONFIRMATION','PAYMENT_CONFIRMED','PAYMENT_REJECTED','PAYMENT_EXPIRED','CANCELLED')),
  UTR_REFERENCE VARCHAR2(64),
  BUYER_SUBMITTED_AT TIMESTAMP,
  IDEMPOTENCY_KEY VARCHAR2(100),
  SELLER_DECISION_BY VARCHAR2(255),
  SELLER_DECISION_AT TIMESTAMP,
  SELLER_REJECTION_REASON VARCHAR2(500),
  EXPIRES_AT TIMESTAMP NOT NULL,
  REFUND_STATUS VARCHAR2(32) DEFAULT 'NOT_REQUESTED' NOT NULL CHECK (REFUND_STATUS IN
    ('NOT_REQUESTED','REQUESTED','INITIATED_BY_SELLER','COMPLETED_BY_SELLER','REJECTED_BY_SELLER')),
  REFUND_REASON VARCHAR2(500),
  REFUND_AMOUNT NUMBER(12,2),
  REFUND_REFERENCE VARCHAR2(100),
  REFUND_UPDATED_BY VARCHAR2(255),
  REFUND_UPDATED_AT TIMESTAMP,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX UX_ORDER_PAYMENT_UTR ON ORDER_SELLER_PAYMENTS(UPPER(UTR_REFERENCE));
CREATE UNIQUE INDEX UX_ORDER_PAYMENT_IDEMPOTENCY ON ORDER_SELLER_PAYMENTS(IDEMPOTENCY_KEY);
CREATE INDEX IDX_ORDER_PAYMENT_BUYER ON ORDER_SELLER_PAYMENTS(BUYER_EMAIL, PAYMENT_STATUS, CREATED_AT);
CREATE INDEX IDX_ORDER_PAYMENT_SELLER ON ORDER_SELLER_PAYMENTS(SELLER_ID, PAYMENT_STATUS, CREATED_AT);
CREATE INDEX IDX_ORDER_PAYMENT_GROUP ON ORDER_SELLER_PAYMENTS(CHECKOUT_GROUP_ID);

CREATE TABLE SELLER_PAYMENT_AUDIT (
  AUDIT_ID VARCHAR2(64) PRIMARY KEY,
  PAYMENT_ID VARCHAR2(64),
  SELLER_ID VARCHAR2(64),
  DESTINATION_ID VARCHAR2(64),
  ACTOR_EMAIL VARCHAR2(255) NOT NULL,
  ACTOR_ROLE VARCHAR2(20) NOT NULL,
  ACTION VARCHAR2(40) NOT NULL,
  PREVIOUS_STATE VARCHAR2(40),
  NEXT_STATE VARCHAR2(40),
  REASON VARCHAR2(500),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IDX_SELLER_PAYMENT_AUDIT ON SELLER_PAYMENT_AUDIT(PAYMENT_ID, CREATED_AT);

CREATE TABLE ORDER_ISSUES (
  ISSUE_ID VARCHAR2(64) PRIMARY KEY,
  ORDER_ID VARCHAR2(64) NOT NULL REFERENCES ORDERS(ORDER_ID),
  BUYER_EMAIL VARCHAR2(255) NOT NULL,
  ISSUE_TYPE VARCHAR2(32) NOT NULL CHECK (ISSUE_TYPE IN
    ('MISSING_ITEM','WRONG_ITEM','DAMAGED','POOR_QUALITY','NOT_DELIVERED','PAYMENT','REFUND','OTHER')),
  DESCRIPTION VARCHAR2(1000) NOT NULL,
  STATUS VARCHAR2(24) DEFAULT 'OPEN' NOT NULL CHECK (STATUS IN ('OPEN','IN_REVIEW','RESOLVED','CLOSED')),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IDX_ORDER_ISSUES_ORDER ON ORDER_ISSUES(ORDER_ID, CREATED_AT);

CREATE TABLE BUYER_CHECKOUT_IDEMPOTENCY (
  BUYER_EMAIL VARCHAR2(255) NOT NULL,
  IDEMPOTENCY_KEY VARCHAR2(100) NOT NULL,
  REQUEST_HASH VARCHAR2(64) NOT NULL,
  ORDER_ID VARCHAR2(64),
  CHECKOUT_GROUP_ID VARCHAR2(64),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_BUYER_CHECKOUT_IDEMPOTENCY PRIMARY KEY (BUYER_EMAIL, IDEMPOTENCY_KEY)
);
CREATE INDEX IDX_CHECKOUT_IDEMPOTENCY_ORDER ON BUYER_CHECKOUT_IDEMPOTENCY(ORDER_ID);
CREATE INDEX IDX_CHECKOUT_IDEMPOTENCY_GROUP ON BUYER_CHECKOUT_IDEMPOTENCY(CHECKOUT_GROUP_ID);
