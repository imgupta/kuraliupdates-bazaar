CREATE TABLE SELLER_ONBOARDING_LEADS (
    LEAD_ID VARCHAR2(64) PRIMARY KEY,
    OWNER_NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(255) NOT NULL,
    PHONE VARCHAR2(10) NOT NULL,
    SOURCE VARCHAR2(40) DEFAULT 'SELLER_REGISTRATION' NOT NULL,
    STATUS VARCHAR2(32) DEFAULT 'STARTED' NOT NULL,
    EMAIL_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    PHONE_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    CONTACT_CONSENT NUMBER(1) DEFAULT 0 NOT NULL,
    CONTACT_CONSENT_AT TIMESTAMP,
    CONTACT_CONSENT_VERSION VARCHAR2(40),
    CALLBACK_REQUESTED NUMBER(1) DEFAULT 0 NOT NULL,
    ASSIGNED_TO VARCHAR2(150),
    CALLBACK_AT TIMESTAMP,
    LAST_CONTACTED_AT TIMESTAMP,
    APPLICATION_ID VARCHAR2(64),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_SELLER_LEAD_STATUS CHECK (STATUS IN ('STARTED','CONTACT_VERIFIED','CALLBACK_REQUESTED','IN_PROGRESS','APPLICATION_SUBMITTED','CONVERTED','NOT_INTERESTED','UNREACHABLE'))
);

CREATE INDEX IDX_SELLER_LEAD_STATUS_CREATED ON SELLER_ONBOARDING_LEADS (STATUS, CREATED_AT);
CREATE INDEX IDX_SELLER_LEAD_PHONE ON SELLER_ONBOARDING_LEADS (PHONE);
CREATE INDEX IDX_SELLER_LEAD_EMAIL ON SELLER_ONBOARDING_LEADS (EMAIL);

CREATE TABLE SELLER_ONBOARDING_LEAD_NOTES (
    NOTE_ID VARCHAR2(64) PRIMARY KEY,
    LEAD_ID VARCHAR2(64) NOT NULL,
    AUTHOR VARCHAR2(150) NOT NULL,
    NOTE_TEXT VARCHAR2(2000) NOT NULL,
    OUTCOME VARCHAR2(40),
    FOLLOW_UP_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_SELLER_LEAD_NOTE FOREIGN KEY (LEAD_ID) REFERENCES SELLER_ONBOARDING_LEADS (LEAD_ID)
);

CREATE INDEX IDX_SELLER_LEAD_NOTES ON SELLER_ONBOARDING_LEAD_NOTES (LEAD_ID, CREATED_AT);

CREATE TABLE SELLER_ONBOARDING_LEAD_AUDIT (
    AUDIT_ID VARCHAR2(64) PRIMARY KEY,
    LEAD_ID VARCHAR2(64) NOT NULL,
    ACTOR VARCHAR2(150) NOT NULL,
    ACTION VARCHAR2(60) NOT NULL,
    DETAILS VARCHAR2(2000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_SELLER_LEAD_AUDIT FOREIGN KEY (LEAD_ID) REFERENCES SELLER_ONBOARDING_LEADS (LEAD_ID)
);

CREATE INDEX IDX_SELLER_LEAD_AUDIT ON SELLER_ONBOARDING_LEAD_AUDIT (LEAD_ID, CREATED_AT);
